"""K5-D, K5A-M2: reproducible fixtures for the "no text" paths, through the production extractor.

The fixtures are checked in under ``tests/fixtures/k5d_no_text/`` and generated by ``make_fixtures.py`` there (the
first test fails if a checked-in file differs from the script's output). Each one goes through
``GlossExtract._process_single_document_pypdfium`` (the safe default route, font repair on) and the test checks the
Markdown text, the font-repair record, the sidecar ``decode_status`` and the ledger page coverage.

What the fixtures showed (K5-D):
- LZW and RunLength content streams were undecodable for the native check: the native text sample said "no text"
  (font repair ``no_text_layer``) and ``decode_status`` said ``unknown`` while PDFium reads the text. The native
  decoder now implements both filters (prefix kept on damage, as FlateDecode): ``complete`` and text found, equal to
  the PDFium reference backend.
- A broken cross-reference table (offsets off, or ``startxref`` out of range) is rebuilt by PDFium and read; the
  native parser does not rebuild it: font repair records the parse error and keeps the original PDF, and every page
  is ``unknown`` with the reason (never ``complete``). Declared limit (the Python reference backend's pypdf rebuilds).
- ``/Count`` larger than the leaves: PDFium trusts it; the missing page fails to load (page coverage ``failed``), its
  status is ``unknown`` (``page unavailable``). ``/Count`` smaller: both read one page.
- No text operator, or only spaces: document-level has_text false (``no_text_layer``), empty Markdown, ``complete``.
- K5A2B-G4: an RC4 document with an empty user password (owner password only; 5 of the 6 encrypted cohort242
  documents) is decrypted by the decode check (``Pdf::open_for_check``; never by analysis or repair) and gets a real
  status; a user-password document or another handler (AES: the sixth) stays ``unknown`` with the reason. The RC4
  documents here are written by pypdf, an independent implementation.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

FIXTURES = Path(__file__).resolve().parent / "fixtures" / "k5d_no_text"
SCHEMA = {"schema": "glossapi.decode_status.v1", "check": "glossapi_rs_pdfrepair.page_decode_status_json"}


def _generator():
    spec = importlib.util.spec_from_file_location("k5d_make_fixtures", FIXTURES / "make_fixtures.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_checked_in_fixtures_are_the_generators_output():
    built = _generator().build()
    assert sorted(built) == sorted(p.name for p in FIXTURES.glob("*.pdf"))
    for name, data in built.items():
        assert (FIXTURES / name).read_bytes() == data, name
    assert sum(map(len, built.values())) < 20_000  # small


def _extract(name, tmp_path, monkeypatch):
    from glossapi.gloss_extract import GlossExtract
    from glossapi.stages.receipts import capture_backend_observations
    monkeypatch.delenv("GLOSSAPI_MARKDOWN_LAYOUT", raising=False)
    extractor = GlossExtract()
    extractor.use_pypdfium_backend = True
    extractor.repair_fonts = True
    extractor.pdf_backend_name = "pypdfium"
    md_dir = tmp_path / "markdown"
    md_dir.mkdir(parents=True)
    source = tmp_path / name
    source.write_bytes((FIXTURES / name).read_bytes())
    with capture_backend_observations() as observations:
        assert extractor._process_single_document_pypdfium(source, output_dir=md_dir)
    sidecar = json.loads((tmp_path / "sidecars/extract" / f"{source.stem}.json").read_text())
    coverage = next(o["details"]["page_coverage"] for o in observations if "page_coverage" in o.get("details", {}))
    return (md_dir / f"{source.stem}.md").read_text(encoding="utf-8"), sidecar, coverage


LONG = "Line 00: a text layer kept behind an old content filter, page one."
SHORT = "A short page of plain text for the cross-reference checks."
# name -> (text the Markdown starts with ('' = empty), page_count, font_repair_status, page statuses, reason fragment,
#          failed pages in the ledger page coverage)
CASES = {
    "lzw_content.pdf": (LONG, 1, "unsupported", ["complete"], None, []),
    "runlength_content.pdf": (LONG, 1, "unsupported", ["complete"], None, []),
    "rebuilt_xref.pdf": (SHORT, 1, "error", ["unknown"], "native parser cannot read the document", []),
    "broken_startxref.pdf": (SHORT, 1, "error", ["unknown"], "native parser cannot read the document", []),
    "count_more.pdf": (SHORT, 3, "error", ["complete", "complete", "unknown"], "page unavailable", [3]),
    "count_less.pdf": (SHORT, 1, "unsupported", ["complete"], None, []),
    "no_text_layer.pdf": ("", 2, "no_text_layer", ["complete", "complete"], None, []),
    "whitespace_text.pdf": ("", 1, "no_text_layer", ["complete"], None, []),
}


@pytest.mark.parametrize("name", sorted(CASES))
def test_no_text_paths_through_the_production_extractor(tmp_path, monkeypatch, name):
    text, pages, repair, statuses, reason, failed = CASES[name]
    md, sidecar, coverage = _extract(name, tmp_path, monkeypatch)
    assert sidecar["extract_status"] == "ok" and sidecar["page_count"] == pages
    assert md.startswith(text) if text else md.strip() == ""
    assert sidecar["font_repair_status"] == repair, sidecar.get("font_repair_error")
    status = sidecar["decode_status"]
    assert {key: status[key] for key in SCHEMA} == SCHEMA and status["pages"] == statuses
    assert coverage["decode_status"] == statuses
    assert coverage["failed"] == failed
    if reason is None:
        assert status["reasons"] == {} and "reason" not in status
    else:
        found = status.get("reason") or " ".join(status["reasons"].values())
        assert reason in found, status
        assert "complete" not in statuses or status["reasons"]  # an undecided page is never reported complete


def test_lzw_and_runlength_text_is_found_by_the_native_sample_like_the_pdfium_reference():
    """The native analysis and the PDFium/pypdf reference backend agree on every fixture the native parser reads; the
    two broken cross-reference fixtures are the declared exception (native parse error, reference rebuild)."""
    import glossapi_rs_pdfrepair as native
    from glossapi.pdf_repair import tounicode as reference
    for name in sorted(CASES):
        path = FIXTURES / name
        mine, theirs = native.analyze_pdf(str(path)), reference.analyze_pdf(path)
        if name in ("rebuilt_xref.pdf", "broken_startxref.pdf"):
            assert mine["error"] and theirs.error is None and theirs.category == "not_embedded", name
            continue
        assert (mine["category"], bool(mine["error"])) == (theirs.category, bool(theirs.error)), name
    assert native.analyze_pdf(str(FIXTURES / "lzw_content.pdf"))["category"] != "no_text_layer"


# ---- K5A2B-G4: documents the native parser refused for encryption -------------------------------------------------
def _encrypted(source, target, **options):
    """``source`` encrypted by pypdf (an independent RC4 implementation): ``PdfWriter.encrypt(**options)``."""
    from pypdf import PdfWriter
    writer = PdfWriter(clone_from=str(source))
    writer.encrypt(**options)
    with open(target, "wb") as handle:
        writer.write(handle)
    return target


def _damaged_flate_page(path):
    """One page whose FlateDecode content stream has its middle third zeroed (the K5P-093 derivation)."""
    import zlib
    content = b"\n".join(b"BT /F1 11 Tf 56 %d Td (Row %02d of a damaged encrypted page) Tj ET" % (780 - 14 * i, i)
                         for i in range(40))
    packed = bytearray(zlib.compress(content))
    a, b = len(packed) // 3, 2 * len(packed) // 3
    packed[a:b] = bytes(b - a)
    make = _generator()
    path.write_bytes(make.write_pdf(make.pages([make.stream(b"/Filter /FlateDecode", bytes(packed))])))
    return path


@pytest.mark.parametrize("algorithm", ["RC4-128", "RC4-40"])
def test_rc4_owner_password_documents_get_a_real_decode_status(tmp_path, monkeypatch, algorithm):
    """An RC4 document whose user password is empty (an owner-password document, which PDFium opens) is decrypted by
    the decode check: complete on an intact page, partial on a damaged one, through the production extractor too. The
    repair path still refuses it (font repair records the error and keeps the original PDF, as before)."""
    import glossapi_rs_pdfrepair as native
    from glossapi.pdf_repair.decode_status import page_decode_status
    good = _encrypted(FIXTURES / "lzw_content.pdf", tmp_path / "good.pdf", user_password="", owner_password="owner",
                      algorithm=algorithm)
    assert b"/Encrypt" in good.read_bytes()
    assert page_decode_status(good, 1)["pages"] == ["complete"]
    damaged = _encrypted(_damaged_flate_page(tmp_path / "plain_damaged.pdf"), tmp_path / "damaged.pdf",
                         user_password="", owner_password="owner", algorithm=algorithm)
    status = page_decode_status(damaged, 1)
    assert status["pages"] == ["partial"] and "FlateDecode" in status["reasons"]["1"], status
    assert "Encrypted PDFs are unsupported" in native.analyze_pdf(str(good))["error"]
    (tmp_path / "x").mkdir()
    source = tmp_path / "x" / "enc.pdf"
    source.write_bytes(good.read_bytes())
    from glossapi.gloss_extract import GlossExtract
    monkeypatch.delenv("GLOSSAPI_MARKDOWN_LAYOUT", raising=False)
    extractor = GlossExtract()
    extractor.use_pypdfium_backend = True
    extractor.repair_fonts = True
    extractor.pdf_backend_name = "pypdfium"
    md_dir = tmp_path / "x" / "markdown"
    md_dir.mkdir()
    assert extractor._process_single_document_pypdfium(source, output_dir=md_dir)
    sidecar = json.loads((tmp_path / "x" / "sidecars/extract/enc.json").read_text())
    assert sidecar["decode_status"]["pages"] == ["complete"] and sidecar["font_repair_status"] == "error"
    assert (md_dir / "enc.md").read_text(encoding="utf-8").startswith(LONG)


def test_user_password_and_unsupported_handlers_stay_unknown(tmp_path):
    """A document that needs a user password, or a handler the check does not decrypt (V 4: AES), stays ``unknown``
    on every page, with the reason; nothing is read as plain."""
    from glossapi.pdf_repair.decode_status import page_decode_status
    locked = _encrypted(FIXTURES / "lzw_content.pdf", tmp_path / "locked.pdf", user_password="secret",
                        owner_password="owner", algorithm="RC4-128")
    status = page_decode_status(locked, 1)
    assert status["pages"] == ["unknown"] and "user password" in status["reason"], status
    data = (FIXTURES / "count_less.pdf").read_bytes()
    at = data.index(b"/Root 1 0 R")
    aes = tmp_path / "aes.pdf"
    aes.write_bytes(data[:at] + b"/Encrypt << /Filter /Standard /V 4 /R 4 /Length 128 /O <00> /U <00> /P -4 >> " + data[at:])
    status = page_decode_status(aes, 1)
    assert status["pages"] == ["unknown"] and "V 4 R 4" in status["reason"], status
