"""Generate `src/layout/tables.rs`: the Python 3.11 Unicode semantics and the regex sources layout v2 needs (K5-A1).

The layout v2 reference (`tests/layout_v2_ref/labels_v2.py`) runs on Python's own Unicode database and `re` module.
The Rust port copies them exactly instead of using Rust's char methods (other sets, other Unicode version):
  str.isspace / isalpha / isdecimal / isdigit / isnumeric / isupper (one char)  -> range tables
  re IGNORECASE (`_sre.unicode_tolower`, `_sre.unicode_iscased`, `re._casefix`)  -> lower map, cased ranges, fixes
  str.casefold (full folding)                                                     -> fold map
  unicodedata.normalize("NFC") (combining class, canonical decomposition, pairs)  -> NFC data
  the reference's regex pattern strings                                           -> copied verbatim
Run with the interpreter the reference is checked on (the Mac venv, Python 3.11 = Unicode 14.0.0):
    python rust/glossapi_rs_pdfrepair/fixtures/generate_layout_tables.py
The output names the Python and Unicode versions; the Rust tests compare these tables with the running Python.
"""
from __future__ import annotations

import _sre
import inspect
import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO / "tests"))
from layout_v2_ref import labels_v2 as lv  # noqa: E402
from re._casefix import _EXTRA_CASES  # noqa: E402

OUT = HERE.parent / "src" / "layout" / "tables.rs"
MAXCP = 0x110000


def ranges(pred):
    out, start = [], None
    for cp in range(MAXCP):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAXCP - 1))
    return out


def ch(cp):
    return chr(cp)


def emit_ranges(name, rs):
    body = ",".join(f"(0x{a:X},0x{b:X})" for a, b in rs)
    return f"pub static {name}: &[(u32, u32)] = &[{body}];\n"


def rust_str(s):
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif 0x20 <= ord(c) < 0x7F:
            out.append(c)
        else:
            out.append("\\u{%X}" % ord(c))
    return '"' + "".join(out) + '"'


def main():
    surrogate = lambda cp: 0xD800 <= cp <= 0xDFFF  # noqa: E731
    parts = [
        "// @generated by fixtures/generate_layout_tables.py -- do not edit.\n",
        f"// Python {sys.version.split()[0]}, unicodedata {unicodedata.unidata_version}.\n",
        "#![allow(clippy::all)]\n",
        f'pub const PYTHON_VERSION: &str = "{sys.version.split()[0]}";\n',
        f'pub const UNIDATA_VERSION: &str = "{unicodedata.unidata_version}";\n',
    ]
    parts.append(emit_ranges("SPACE", ranges(lambda c: ch(c).isspace())))
    parts.append(emit_ranges("ALPHA", ranges(lambda c: ch(c).isalpha())))
    parts.append(emit_ranges("DECIMAL", ranges(lambda c: ch(c).isdecimal())))
    parts.append(emit_ranges("DIGIT", ranges(lambda c: ch(c).isdigit())))
    parts.append(emit_ranges("NUMERIC", ranges(lambda c: ch(c).isnumeric())))
    parts.append(emit_ranges("UPPER", ranges(lambda c: ch(c).isupper())))
    parts.append(emit_ranges("CASED", ranges(lambda c: bool(_sre.unicode_iscased(c)))))
    lower = [(c, _sre.unicode_tolower(c)) for c in range(MAXCP) if _sre.unicode_tolower(c) != c]
    parts.append("pub static LOWER: &[(u32, u32)] = &[" + ",".join(f"(0x{a:X},0x{b:X})" for a, b in lower) + "];\n")
    fixes = sorted(_EXTRA_CASES.items())
    parts.append("pub static EXTRA_CASES: &[(u32, &[u32])] = &[" + ",".join(
        f"(0x{k:X},&[{','.join(f'0x{x:X}' for x in v)}])" for k, v in fixes) + "];\n")
    fold = []
    for c in range(MAXCP):
        if surrogate(c):
            continue
        f = ch(c).casefold()
        if f != ch(c):
            fold.append((c, [ord(x) for x in f]))
    parts.append("pub static CASEFOLD: &[(u32, &[u32])] = &[" + ",".join(
        f"(0x{a:X},&[{','.join(f'0x{x:X}' for x in v)}])" for a, v in fold) + "];\n")
    # NFC data: combining classes (ranges of equal class), single-level canonical decompositions, composition pairs
    ccc, start, cur = [], None, 0
    for c in range(MAXCP + 1):
        k = unicodedata.combining(ch(c)) if c < MAXCP else 0
        if k != cur:
            if cur:
                ccc.append((start, c - 1, cur))
            start, cur = c, k
    parts.append("pub static CCC: &[(u32, u32, u8)] = &[" + ",".join(f"(0x{a:X},0x{b:X},{k})" for a, b, k in ccc) + "];\n")
    decomp, pairs = [], []
    for c in range(MAXCP):
        d = unicodedata.decomposition(ch(c))
        if not d or d.startswith("<"):
            continue
        cps = [int(x, 16) for x in d.split()]
        decomp.append((c, cps))
        if len(cps) == 2 and unicodedata.normalize("NFC", ch(c)) == ch(c):
            pairs.append(((cps[0], cps[1]), c))
    pairs.sort()
    parts.append("pub static DECOMP: &[(u32, &[u32])] = &[" + ",".join(
        f"(0x{a:X},&[{','.join(f'0x{x:X}' for x in v)}])" for a, v in decomp) + "];\n")
    parts.append("pub static COMPOSE: &[((u32, u32), u32)] = &[" + ",".join(
        f"((0x{a:X},0x{b:X}),0x{c:X})" for (a, b), c in pairs) + "];\n")
    parts.append(emit_ranges("NFC_FIRST", ranges_from(sorted({a for (a, _), _ in pairs}))))
    parts.append(emit_ranges("NFC_LAST", ranges_from(sorted({b for (_, b), _ in pairs}))))
    # regex sources, verbatim from the reference (name, pattern, IGNORECASE)
    pats = []
    for name in ("BOLD_NAME", "ITALIC_NAME", "MATH_FONT", "BULLET", "ENUM", "NUMBERED", "SECNUM", "CAPTION",
                 "FOOTMARK", "PAGE_NUM", "LINE_START", "FIGWORD"):
        p = getattr(lv, name)
        assert p.flags & ~re.I == re.U, (name, p.flags)
        pats.append((name, p.pattern, bool(p.flags & re.I)))
    src = inspect.getsource(lv)
    inline = {"TABLE_RULE": r"^\s*\|?\s*:?-{3,}", "MARK_ALONE": r"\s*\S{1,3}\s*"}
    for name, p in inline.items():
        assert repr(p) in src or f'r"{p}"' in src, name
        pats.append((name, p, False))
    for name, p, icase in pats:
        parts.append(f"pub const {name}: (&str, bool) = ({rust_str(p)}, {str(icase).lower()});\n")
    parts.append("pub static OPS: &[u32] = &[" + ",".join(f"0x{ord(c):X}" for c in sorted(lv.OPS)) + "];\n")
    parts.append("pub static LOOKALIKE: &[(u32, u32)] = &[" + ",".join(
        f"(0x{k:X},0x{ord(v):X})" for k, v in sorted(lv.LOOKALIKE.items())) + "];\n")
    OUT.write_text("".join(parts))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


def ranges_from(cps):
    out = []
    for c in cps:
        if out and out[-1][1] == c - 1:
            out[-1] = (out[-1][0], c)
        else:
            out.append((c, c))
    return out


if __name__ == "__main__":
    main()
